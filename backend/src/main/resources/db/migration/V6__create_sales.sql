
-- STOCK-028: Sistema de ventas

-- 1. Cabecera de ventas
CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total NUMERIC(12,2) NOT NULL,

    CONSTRAINT chk_sales_total
        CHECK (total >= 0)
);

-- 2. Líneas de cada venta
CREATE TABLE sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL,

    CONSTRAINT fk_sale_items_sale
        FOREIGN KEY (sale_id) REFERENCES sales(id),

    CONSTRAINT fk_sale_items_product
        FOREIGN KEY (product_id) REFERENCES products(id),

    CONSTRAINT chk_sale_items_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_sale_items_price
        CHECK (unit_price >= 0),

    CONSTRAINT chk_sale_items_subtotal
        CHECK (subtotal >= 0)
);

-- 3. Índices
CREATE INDEX idx_sale_items_sale_id
    ON sale_items(sale_id);

CREATE INDEX idx_sale_items_product_id
    ON sale_items(product_id);

CREATE INDEX idx_sales_created_at
    ON sales(created_at DESC);

-- 4. vinculr las salidas de inventario con las ventas
ALTER TABLE stock_movements
ADD COLUMN sale_id BIGINT;

ALTER TABLE stock_movements
ADD CONSTRAINT fk_stock_movements_sale
    FOREIGN KEY (sale_id) REFERENCES sales(id);

CREATE INDEX idx_stock_movements_sale_id
    ON stock_movements(sale_id);
